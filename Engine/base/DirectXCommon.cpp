ModelData LoadObjFile(const std::string& directoryPath, const std::string& fileName)
{
	ModelData modelData;
	std::vector<Vector4> positions;
	std::vector<Vector3> normals;
	std::vector<Vector2> texcoords;
	std::string line;

	std::ifstream file(directoryPath + "/" + fileName);

	if (!file.is_open())
	{
		Log("Error: Failed to open OBJ file: " + directoryPath + "/" + fileName + "\n");
		return modelData;
	}

	MeshData currentMesh;
	std::string currentMtlFile = "";

	while (std::getline(file, line))
	{
		std::string identifier;
		std::istringstream s(line);
		s >> identifier;

		if (identifier == "mtllib")
		{
			s >> currentMtlFile;
		}
		else if (identifier == "usemtl")
		{
			if (!currentMesh.vertices.empty())
			{
				modelData.meshes.push_back(currentMesh);
				currentMesh = MeshData();
			}
			std::string materialName;
			s >> materialName;
			if (!currentMtlFile.empty())
			{
				currentMesh.material = LoadMaterialTemplateFile(directoryPath, currentMtlFile);
			}
		}
		else if (identifier == "v")
		{
			Vector4 position;
			s >> position.x >> position.y >> position.z;
			position.w = 1.0f;
			positions.push_back(position);
		}
		else if (identifier == "vt")
		{
			Vector2 texcoord;
			s >> texcoord.x >> texcoord.y;
			texcoord.y = 1.0f - texcoord.y;
			texcoords.push_back(texcoord);
		}
		else if (identifier == "vn")
		{
			Vector3 normal;
			s >> normal.x >> normal.y >> normal.z;
			normals.push_back(normal);
		}
		else if (identifier == "f")
		{
			VertexData triangle[3];

			for (int32_t faceVertex = 0; faceVertex < 3; ++faceVertex)
			{
				std::string vertexDefinition;
				s >> vertexDefinition;

				std::istringstream v(vertexDefinition);
				std::string indexElement;

				size_t positionIndex = 0;
				if (std::getline(v, indexElement, '/') && !indexElement.empty()) {
					positionIndex = std::stoull(indexElement) - 1;
				}

				size_t texcoordIndex = 0;
				bool hasTexcoord = false;
				if (std::getline(v, indexElement, '/') && !indexElement.empty()) {
					texcoordIndex = std::stoull(indexElement) - 1;
					hasTexcoord = true;
				}

				size_t normalIndex = 0;
				bool hasNormal = false;
				if (std::getline(v, indexElement, '/') && !indexElement.empty()) {
					normalIndex = std::stoull(indexElement) - 1;
					hasNormal = true;
				}

				VertexData vertex{};
				if (positionIndex < positions.size()) {
					vertex.position = positions[positionIndex];
				}

				if (hasTexcoord && texcoordIndex < texcoords.size()) {
					vertex.u = texcoords[texcoordIndex].x;
					vertex.v = texcoords[texcoordIndex].y;
				}
				else {
					vertex.u = 0.0f;
					vertex.v = 0.0f;
				}

				if (hasNormal && normalIndex < normals.size()) {
					vertex.normal = normals[normalIndex];
				}
				else {
					vertex.normal = Vector3{ 0.0f, 0.0f, -1.0f };
				}

				vertex.position.x *= -1.0f;
				vertex.normal.x *= -1.0f;

				triangle[faceVertex] = vertex;
			}

			currentMesh.vertices.push_back(triangle[2]);
			currentMesh.vertices.push_back(triangle[1]);
			currentMesh.vertices.push_back(triangle[0]);
		}
	}

	if (!currentMesh.vertices.empty())
	{
		modelData.meshes.push_back(currentMesh);
	}

	return modelData;
}

MaterialData LoadMaterialTemplateFile(const std::string& directoryPath, const std::string& fileName)
{
	MaterialData materialData;
	std::string line;
	std::ifstream file(directoryPath + "/" + fileName);

	if (!file.is_open())
	{
		Log("Warning: Failed to open MTL file: " + directoryPath + "/" + fileName + "\n");
		return materialData;
	}

	while (std::getline(file, line))
	{
		std::string identifier;
		std::istringstream s(line);
		s >> identifier;

		if (identifier == "map_Kd")
		{
			std::string textureFileName;
			s >> textureFileName;
			materialData.textureFilePath = directoryPath + "/" + textureFileName;
			break;
		}
	}
	return materialData;
}

ID3D12Resource* UploadTextureData(
	ID3D12Resource* texture,
	const DirectX::ScratchImage& mipImages,
	ID3D12Device* device,
	ID3D12GraphicsCommandList* commandList)
{
	std::vector<D3D12_SUBRESOURCE_DATA> subresources;
	DirectX::PrepareUpload(device, mipImages.GetImages(), mipImages.GetImageCount(), mipImages.GetMetadata(), subresources);

	uint64_t intermediateSize = GetRequiredIntermediateSize(texture, 0, UINT(subresources.size()));
	ID3D12Resource* intermediateResource = CreateBufferResource(device, intermediateSize);

	UpdateSubresources(commandList, texture, intermediateResource, 0, 0, UINT(subresources.size()), subresources.data());

	D3D12_RESOURCE_BARRIER barrier{};
	barrier.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
	barrier.Flags = D3D12_RESOURCE_BARRIER_FLAG_NONE;
	barrier.Transition.pResource = texture;
	barrier.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
	barrier.Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_DEST;
	barrier.Transition.StateAfter = D3D12_RESOURCE_STATE_GENERIC_READ;
	commandList->ResourceBarrier(1, &barrier);

	return intermediateResource;
}

